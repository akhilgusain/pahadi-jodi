CREATE TABLE conversation (
    id              UUID PRIMARY KEY,
    user_a          UUID NOT NULL,
    user_b          UUID NOT NULL,
    last_message_id BIGINT,
    last_message_at TIMESTAMP WITH TIME ZONE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_conversation_pair UNIQUE (user_a, user_b)
);
CREATE INDEX idx_conversation_a ON conversation (user_a);
CREATE INDEX idx_conversation_b ON conversation (user_b);

CREATE TABLE chat_message (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id    UUID NOT NULL REFERENCES conversation (id),
    sender_id          UUID NOT NULL,
    recipient_id       UUID NOT NULL,
    type               VARCHAR(12) NOT NULL,
    body               VARCHAR(4000),
    media_url          VARCHAR(1000),
    media_duration_sec INT,
    client_msg_id      VARCHAR(64) NOT NULL,
    status             VARCHAR(10) NOT NULL,
    flagged            BOOLEAN NOT NULL DEFAULT FALSE,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    delivered_at       TIMESTAMP WITH TIME ZONE,
    read_at            TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_message_client UNIQUE (conversation_id, sender_id, client_msg_id)
);
CREATE INDEX idx_message_conversation ON chat_message (conversation_id, id);
CREATE INDEX idx_message_recipient_status ON chat_message (recipient_id, status);

CREATE TABLE message_reaction (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id BIGINT NOT NULL REFERENCES chat_message (id),
    user_id    UUID NOT NULL,
    emoji      VARCHAR(16) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_reaction_user UNIQUE (message_id, user_id)
);

CREATE TABLE chat_match (
    id         UUID PRIMARY KEY,
    user_a     UUID NOT NULL,
    user_b     UUID NOT NULL,
    match_ref  VARCHAR(64),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_chat_match_pair UNIQUE (user_a, user_b)
);

CREATE TABLE call_session (
    id                        UUID PRIMARY KEY,
    conversation_id           UUID NOT NULL REFERENCES conversation (id),
    caller_id                 UUID NOT NULL,
    callee_id                 UUID NOT NULL,
    mode                      VARCHAR(8) NOT NULL,
    state                     VARCHAR(12) NOT NULL,
    caller_recording_consent  BOOLEAN NOT NULL DEFAULT FALSE,
    callee_recording_consent  BOOLEAN NOT NULL DEFAULT FALSE,
    created_at                TIMESTAMP WITH TIME ZONE NOT NULL,
    answered_at               TIMESTAMP WITH TIME ZONE,
    ended_at                  TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_call_conversation_state ON call_session (conversation_id, state);
CREATE INDEX idx_call_state_created ON call_session (state, created_at);
