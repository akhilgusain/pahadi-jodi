CREATE TABLE moderation_case (
    id              UUID PRIMARY KEY,
    content_type    VARCHAR(10)  NOT NULL,
    ref_id          VARCHAR(100) NOT NULL,
    subject_user_id UUID,
    source          VARCHAR(10)  NOT NULL,
    decision        VARCHAR(6)   NOT NULL,
    labels          VARCHAR(500) NOT NULL,
    score           DOUBLE PRECISION NOT NULL,
    status          VARCHAR(12)  NOT NULL,
    priority        INT NOT NULL,
    assigned_to     UUID,
    due_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    resolution      VARCHAR(10),
    resolved_by     UUID,
    resolved_at     TIMESTAMP WITH TIME ZONE,
    note            VARCHAR(500),
    excerpt         VARCHAR(300),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_case_queue ON moderation_case (status, priority, due_at);
CREATE INDEX idx_case_subject ON moderation_case (subject_user_id);

CREATE TABLE user_report (
    id             UUID PRIMARY KEY,
    reporter_id    UUID NOT NULL,
    target_user_id UUID NOT NULL,
    reason         VARCHAR(30) NOT NULL,
    details        VARCHAR(2000),
    evidence_ref   VARCHAR(200),
    case_id        UUID,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_report_target ON user_report (target_user_id, created_at);
CREATE INDEX idx_report_pair ON user_report (reporter_id, target_user_id, created_at);

CREATE TABLE user_strike (
    id         UUID PRIMARY KEY,
    user_id    UUID NOT NULL,
    case_id    UUID,
    points     INT NOT NULL,
    reason     VARCHAR(200),
    revoked    BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_strike_user ON user_strike (user_id, created_at);

CREATE TABLE user_status (
    user_id    UUID PRIMARY KEY,
    status     VARCHAR(10) NOT NULL,
    until      TIMESTAMP WITH TIME ZONE,
    source     VARCHAR(10) NOT NULL,
    reason     VARCHAR(300),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE appeal (
    id            UUID PRIMARY KEY,
    user_id       UUID NOT NULL,
    case_id       UUID,
    message       VARCHAR(2000) NOT NULL,
    status        VARCHAR(12) NOT NULL,
    decided_by    UUID,
    decision_note VARCHAR(500),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    resolved_at   TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_appeal_status ON appeal (status, created_at);

-- Append-only decision log, hash-chained: hash = SHA-256(prev_hash | case | actor | action | detail | created_at_ms)
CREATE TABLE decision_audit (
    seq        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id    UUID,
    actor      VARCHAR(64)  NOT NULL,
    action     VARCHAR(40)  NOT NULL,
    detail     VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    prev_hash  VARCHAR(64) NOT NULL,
    hash       VARCHAR(64) NOT NULL
);
-- Single row, locked FOR UPDATE on every append so that concurrent writers cannot fork the chain.
CREATE TABLE audit_head (
    id        INT PRIMARY KEY,
    last_hash VARCHAR(64) NOT NULL
);
